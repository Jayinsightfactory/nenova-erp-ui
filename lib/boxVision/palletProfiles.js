function pallet8Box(photoKey, seq, layerNo, fields) {
  return {
    boxId: `${photoKey}-b${seq}`,
    serialNo: `${PALLET8_AWB.replace(/-/g, '')}-L${layerNo}-B${String(seq).padStart(2, '0')}`,
    lineNo: String(layerNo),
    boxSeq: String(seq),
    orderYear: 2026,
    orderWeek: '47-02',
    countryName: '중국/콜롬비아',
    status: 'COUNTED',
    ...fields,
  };
}

