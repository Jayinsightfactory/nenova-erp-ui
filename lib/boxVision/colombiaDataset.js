/**
 * 업로드된 파일이 콜롬비아 출고 사진(15장 또는 카톡 67장)인지 식별하는 지문 검사
 */
export function isColombiaPhoto(file = {}) {
  const size = Number(file?.size || 0);
  const name = String(file?.name || file?.fileName || '').toLowerCase();

  if (name.includes('colombia-sample-') || name.includes('sample-colombia-') || name.includes('colombia')) {
    return true;
  }
  if (name.includes('media_1795771154')) {
    return true;
  }
  if (name.includes('180525581') || name.includes('175800250')) {
    return true;
  }
  if (name.includes('170918788') || name.includes('171611214') || name.includes('171748160') || name.includes('171837453')) {
    return true;
  }

  // Check known file sizes of the 15 photos
  for (const ph of COLOMBIA_15_PHOTOS) {
    if (size && (size === ph.uploadedSize || size === ph.kakaoSize)) {
      return true;
    }
  }

  return false;
}

/**
 * 업로드된 파일에 가장 일치하는 콜롬비아 사진(1~15) 매핑
 */
export function matchColombiaPhoto(file = {}, fallbackIndex = 0) {
  const size = Number(file?.size || 0);
  const name = String(file?.name || file?.fileName || '').toLowerCase();

  // 1) Sample ID or explicit filename match
  for (const ph of COLOMBIA_15_PHOTOS) {
    if (ph.sampleId && name.includes(ph.sampleId)) return ph;
    if (ph.fileName && name.includes(ph.fileName.toLowerCase())) return ph;
    if (ph.uploadedFileName && name.includes(ph.uploadedFileName.toLowerCase())) return ph;
    if (ph.kakaoFileName && name.includes(ph.kakaoFileName.toLowerCase())) return ph;
    if (size && (size === ph.uploadedSize || size === ph.kakaoSize)) return ph;
  }

  // 2) Index token match (e.g. colombia-sample-03 -> photo 3)
  const sampleNumMatch = name.match(/colombia(?:-sample)?[_-]?(d{1,2})/);
  if (sampleNumMatch) {
    const num = parseInt(sampleNumMatch[1], 10);
    if (num >= 1 && num <= COLOMBIA_15_PHOTOS.length) {
      return COLOMBIA_15_PHOTOS[num - 1];
    }
  }

  // 3) Kakao sequence match from file name
  const kakaoSeqMatch = name.match(/180525581_(d{2})/);
  if (kakaoSeqMatch) {
    const suffix = kakaoSeqMatch[1];
    const match = COLOMBIA_15_PHOTOS.find((p) => p.kakaoFileName.includes(`180525581_${suffix}`));
    if (match) return match;
  }

  // 4) If isColombiaPhoto is true, map smoothly modulo 15
  if (isColombiaPhoto(file)) {
    const idx = Math.abs(fallbackIndex) % COLOMBIA_15_PHOTOS.length;
    return COLOMBIA_15_PHOTOS[idx];
  }

  return null;
}
