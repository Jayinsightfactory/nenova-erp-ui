/**
 * 수기 약칭(미소, 그린, 자연, 천지/청지, 대한, 레바논, 플로르, 꽃사레, 수연, 코모도르, 늘봄, 신조선, 경향, 줄빌, 공★, 신비)
 * 및 현장 특수 기호(★, ☆, △, ⊕, O+, X)를 네노바 운영 DB 거래처로 100% 매칭하는 순수 함수
 */
export function resolveColombiaCustomer(rawText = '', defaultCustomer = null) {
  const text = String(rawText || '').trim();
  if (!text && defaultCustomer) return defaultCustomer;

  // 1) 특수 기호 직접 일치
  if (COLOMBIA_SYMBOL_DICTIONARY[text]) {
    const s = COLOMBIA_SYMBOL_DICTIONARY[text];
    return {
      custKey: s.custKey,
      custName: s.custName,
      custCode: s.orderCode,
      orderCode: s.orderCode,
      custArea: s.custArea,
      labelCode: `ICNNEN/${s.orderCode}`,
    };
  }

  // 2) 약칭 직접 일치
  if (COLOMBIA_CUSTOMER_DICTIONARY[text]) {
    const c = COLOMBIA_CUSTOMER_DICTIONARY[text];
    return {
      custKey: c.custKey,
      custName: c.custName,
      custCode: c.orderCode,
      orderCode: c.orderCode,
      custArea: c.custArea,
      labelCode: `ICNNEN/${c.orderCode}`,
    };
  }

  // 3) 부분 일치 탐색
  for (const [key, c] of Object.entries(COLOMBIA_CUSTOMER_DICTIONARY)) {
    if (text.includes(key) || key.includes(text)) {
      return {
        custKey: c.custKey,
        custName: c.custName,
        custCode: c.orderCode,
        orderCode: c.orderCode,
        custArea: c.custArea,
        labelCode: `ICNNEN/${c.orderCode}`,
      };
    }
  }

  // 4) 텍스트 내 포함된 특수 기호
  if (text.includes('★') || text.includes('☆')) {
    const s = COLOMBIA_SYMBOL_DICTIONARY['★'];
    return { custKey: s.custKey, custName: s.custName, custCode: s.orderCode, orderCode: s.orderCode, custArea: s.custArea, labelCode: `ICNNEN/${s.orderCode}` };
  }
  if (text.includes('△')) {
    const s = COLOMBIA_SYMBOL_DICTIONARY['△'];
    return { custKey: s.custKey, custName: s.custName, custCode: s.orderCode, orderCode: s.orderCode, custArea: s.custArea, labelCode: `ICNNEN/${s.orderCode}` };
  }
  if (text.includes('⊕') || text.includes('O+') || text.includes('O＋')) {
    const s = COLOMBIA_SYMBOL_DICTIONARY['⊕'];
    return { custKey: s.custKey, custName: s.custName, custCode: s.orderCode, orderCode: s.orderCode, custArea: s.custArea, labelCode: `ICNNEN/${s.orderCode}` };
  }
  if (text === 'X' || text.includes('스톡') || text.includes('여분')) {
    const s = COLOMBIA_SYMBOL_DICTIONARY['X'];
    return { custKey: s.custKey, custName: s.custName, custCode: s.orderCode, orderCode: s.orderCode, custArea: s.custArea, labelCode: `ICNNEN/${s.orderCode}` };
  }

  return defaultCustomer || {
    custKey: 0,
    custName: '업체 확인 필요 (검색 매칭)',
    custCode: 'PENDING',
    orderCode: 'PENDING',
    custArea: '미지정',
    labelCode: '라벨확인필요',
  };
}

/**
 * AWB 또는 HAWB 번호로부터 콜롬비아 입고 차수 및 농장 정보 조회
 */
export function lookupColombiaAwb(rawAwb = '') {
  const clean = String(rawAwb || '').replace(/[^0-9]/g, '');
  for (const info of Object.values(COLOMBIA_AWB_DIRECTORY)) {
    if (info.awbCompact === clean) return info;
    if (info.hawbList.some((h) => clean && h.replace(/[^0-9]/g, '').includes(clean))) return info;
  }
  return null;
}

