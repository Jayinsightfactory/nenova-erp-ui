/**
 * 시안 ID('A'|'B'|'C'|'ALL')에 대응하는 CSS 변수 맵을 반환한다.
 * @param {string} planId
 * @param {string} [wbMode='dark']
 * @returns {Record<string, string>}
 */
export function getPlanTokenVars(planId, wbMode = 'dark') {
  const paletteKey = planId === 'ALL' ? (wbMode === 'clear' ? 'ALL_CLEAR' : 'ALL_DARK') : planId;
  const base = PLAN_TOKEN_PALETTES[paletteKey];
  if (!base) return {};
  return {
    ...base,
    '--pm-bg': base['--trw-bg'],
    '--pm-surface': base['--trw-surface'],
    '--pm-surface2': base['--trw-surface-2'],
    '--pm-ink': base['--trw-ink'],
    '--pm-muted': base['--trw-muted'],
    '--pm-line': base['--trw-line'],
    '--pm-accent': base['--trw-accent'],
    '--pm-accent-ink': base['--trw-accent-ink'],
    '--pm-ok': base['--trw-ok'],
    '--pm-ok-bg': base['--trw-ok-bg'],
    '--pm-ok-ink': base['--trw-ok-ink'],
    '--pm-idle': base['--trw-warn'],
    '--pm-idle-bg': base['--trw-warn-bg'],
    '--pm-idle-ink': base['--trw-warn-ink'],
    '--pm-err': base['--trw-err'],
    '--pm-link': base['--trw-link'],
    '--pm-radius': base['--trw-radius'],
    '--pmk-primary': base['--trw-accent'],
    '--pmk-primary-hover': base['--trw-accent'],
    '--pmk-primary-down': base['--trw-accent'],
    '--pmk-primary-ink': base['--trw-accent-ink'],
    '--pmk-sec-bg': base['--trw-surface'],
    '--pmk-sec-hover': base['--trw-surface-2'],
    '--pmk-sec-ink': base['--trw-ink'],
    '--pmk-sec-border': base['--trw-line'],
    '--pmk-chip-bg': base['--trw-surface-2'],
    '--pmk-chip-ink': base['--trw-ink'],
    '--pmk-on-bg': base['--trw-accent'],
    '--pmk-on-ink': base['--trw-accent-ink'],
    '--pmk-ink': base['--trw-ink'],
    '--pmk-link': base['--trw-link'],
    '--pmk-tab-ink': base['--trw-muted'],
    '--pmk-tab-on': base['--trw-accent'],
    '--pmk-focus': base['--trw-accent'],
    '--pmk-radius': base['--trw-radius'],
    '--pmk-shadow': 'none',
    colorScheme: planId === 'C' || (planId === 'ALL' && wbMode !== 'clear') ? 'dark' : 'light',
  };
}
