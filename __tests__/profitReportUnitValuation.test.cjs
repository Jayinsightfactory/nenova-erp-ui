const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const { reportUnitQuantity: q, reportUnitQuantitySql, completeReportQuantitySumSql } = await import('../lib/profitReportUnitQuantity.mjs');
  const { selectReportInventoryValuation: value } = await import('../lib/profitReportValuation.mjs');
  const { getHistoricalTaxableRate: rate } = await import('../lib/profitReportHistoricalCustoms.js');
  assert.equal(rate('2026','17','호주'),1052.8);
  assert.equal(rate('2026','18','호주'),null,'conflicting originals are quarantined');
  assert.equal(rate('2025','17','호주'),null);
  assert.equal(rate(null,'17','호주'),null);
  assert.equal(rate('2026','41','호주'),null);
  const { computeProfitRow: calc, computeProfitTotals: total, calcPurchaseRatio } = await import('../lib/profitReportCalc.js');
  assert.equal(q({ estUnit:'단', estQuantity:4, boxQuantity:4, bunchQuantity:100, steamQuantity:2500 }),100);
  assert.equal(q({ estUnit:'송이', estQuantity:4, boxQuantity:4, steamQuantity:120 }),120);
  assert.equal(q({ estUnit:'박스', boxQuantity:4, bunchQuantity:100 }),4);
  assert.equal(q({ estUnit:'BUNCH', boxQuantity:4, bunchOf1Box:25 }),100);
  assert.equal(q({ estUnit:'STEAM', boxQuantity:4, steamOf1Box:30 }),120);
  assert.equal(q({ estUnit:'단', estQuantity:4, boxQuantity:4, bunchOf1Box:0 }),null);
  assert.equal(q({ estUnit:'?', estQuantity:4, boxQuantity:4 }),null);
  assert.equal(q({ estUnit:'단', bunchQuantity:0 }),null);
  assert.throws(()=>reportUnitQuantitySql('untrusted'));
  assert.match(completeReportQuantitySumSql(reportUnitQuantitySql('sd')),/COUNT\(\*\)=COUNT/);
  const input={ year:'2026',major:'04',week:'04-02',average:{value:123.456},direct:999,directStatus:'VERIFIED',historical:{value:8}};
  assert.deepEqual(value(input),value({...input}),'F(04) and E(05) share the valuation of 2026/04');
  assert.equal(value({...input,average:null,direct:0}).value,0);
  assert.equal(value({...input,year:null}),null);
  assert.notDeepEqual(value(input).sources,value({...input,year:'2025'}).sources);
  const row={category:'호주',manual:{},auto:{N:1000,L:0,O:0,Q:2,R:100,S:3,H:10,E:100,F:20}};
  assert.equal(calc(row).J,410);
  for(const R of [null,undefined,0,-1,NaN]) {
    const result=calc({...row,auto:{...row.auto,R}});
    for(const k of ['P','T','G','I','J','K']) assert.equal(result[k],null,`${k} pending without rate`);
    const totals=total([{category:row.category,calc:result}]);
    assert.equal(totals.J,null);assert.equal(totals.K,null);assert.equal(totals.P,null);
    assert.equal(calcPurchaseRatio(result,totals),null);
  }
  assert.equal(calc({...row,auto:{...row.auto,Q:0,S:0,R:null}}).G,0,'no foreign cost needs no rate');
  assert.equal(calc({...row,auto:{...row.auto,E:null}}).J,null);
  assert.equal(calc({...row,auto:{...row.auto,F:null}}).J,null);
  assert.equal(calc({...row,manual:{R:0}}).J,null,'explicit invalid override does not fall back');
  assert.equal(calc({...row,manual:{R:200}}).P,400);
  const { buildMonthlyProfitSummary } = await import('../lib/profitReportMonthly.js');
  const month = buildMonthlyProfitSummary([{major:'01',period:{startDate:'2026-01-01',endDate:'2026-01-06'},totals:{C:100,F:0,J:null,G:null,I:null,P:null,T:null}}],'2026').months[0];
  assert.equal(month.totals.J,null); assert.equal(month.totals.K,null); assert.equal(month.totals.P,null);
  const api=fs.readFileSync('pages/api/sales/profit-report.js','utf8');
  assert.equal((api.match(/selectReportInventoryValuation\(\{/g)||[]).length,2);
  assert.match(api,/preferLive: true/);
  const page=fs.readFileSync('pages/sales/profit-report.js','utf8');
  const refresh=page.slice(page.indexOf('const refreshSnapshot ='),page.indexOf('  useEffect',page.indexOf('const refreshSnapshot =')));
  assert(!refresh.includes("method: 'POST'"));assert(refresh.includes('auditLive=1'));
  const source=fs.readFileSync('lib/profitReport.js','utf8');
  const auto=source.slice(source.indexOf('export async function autoStockUnitPrices'),source.indexOf('export function resolveAutoStockPrice'));
  assert(auto.includes('sm.OrderYear=@yr'));assert(auto.includes("ISNULL(wm.OrderYear,'')=@yr"));
  assert(!/\b(UPDATE|INSERT|DELETE|MERGE|EXEC)\s/i.test(auto));
  assert(!auto.includes('SUM(sd.EstQuantity)'));assert(!auto.includes('SUM(wd.EstQuantity)'));
  console.log('profitReportUnitValuation: units, partial denominators, rates, totals, E/F policy, year and read-only UI passed');
})().catch(e=>{console.error(e);process.exitCode=1});
