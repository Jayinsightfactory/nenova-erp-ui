import assert from 'node:assert/strict';
import {stockPageScope,stockPageDocuments,stockPageTabs} from '../lib/kakaoStockPages.js';
import {calculateLedger} from '../lib/kakaoStockLedger.js';
const snapshot=(id,pageId,week,extra={})=>({FavoriteKey:id,FilterData:JSON.stringify({version:2,pageId,week,title:'동일 이름',base:'문라이트 3',events:[],...extra})});
const rows=[snapshot(1,'a','2026-43-01'),snapshot(2,'a','2026-43-01',{events:[{id:'add',product:'문라이트',customer:'주광',qty:1,mode:'ADD',unit:'박스'}]}),snapshot(3,'b','2026-43-01'),snapshot(4,'a','2025-43-01'),snapshot(5,'a','2026-44-01')];
const docs=stockPageDocuments(rows);
assert.equal(docs.length,4);
assert.equal(docs.find(d=>d.pageId==='a'&&d.week==='2026-43-01').item.FavoriteKey,2);
assert.equal(calculateLedger(docs.find(d=>d.pageId==='a'&&d.week==='2026-43-01').base,docs.find(d=>d.pageId==='a'&&d.week==='2026-43-01').events).rows[0].remaining,2);
assert.equal(docs.find(d=>d.pageId==='b').events.length,0);
assert.equal(docs.find(d=>d.week==='2025-43-01').events.length,0);
assert.notEqual(stockPageScope('a','2025-43-01'),stockPageScope('a','2026-43-01'));
assert.notEqual(stockPageScope('a','2026-43-01'),stockPageScope('b','2026-43-01'));
assert.equal(stockPageTabs(docs,{pageId:'a',title:'새 이름'}).length,2);
assert.equal(stockPageTabs(docs,{pageId:'a',title:'새 이름'}).find(d=>d.pageId==='a').title,'새 이름');
const legacy=[snapshot(6,null,'2026-43-01',{version:1}),snapshot(7,null,'2026-43-01',{version:1}),snapshot(8,null,'2025-43-01',{version:1})];
assert.equal(stockPageDocuments(legacy).length,2);
assert.equal(stockPageDocuments([snapshot(9,'a','2026-00-01'),{FavoriteKey:10,FilterData:'invalid'},snapshot(11,'a','2026-43-01',{base:'문라이트 3\n문라이트 2'}),snapshot(12,'','2026-43-01')]).length,0);
assert.equal(stockPageDocuments([snapshot(13,'empty','2026-43-01',{base:''})]).length,1);
console.log('PASS page IDs, duplicate scope, cross-year/week isolation, latest snapshots, v1 compatibility, corrupt snapshot exclusion, empty page metadata');
