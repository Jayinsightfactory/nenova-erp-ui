import assert from 'node:assert/strict';
import { assertDefectSourceFacts } from '../lib/defectSourceFacts.js';
const brut='42-1차 카네이션 불량\n주광농원\n브르트 5단';
const fact={customerAliases:['주광','주광농원'],itemTokens:['브르트'],quantity:5,unit:'단'};
assert.equal(assertDefectSourceFacts(brut,fact),true);
assert.throws(()=>assertDefectSourceFacts(brut,{...fact,quantity:15}));
const multi='43-1 수국\n화이트 25대\n블루 6대\n대한';
const white={customerAliases:['대한'],itemTokens:['화이트'],quantity:25,unit:'스팀(대)'};
assert.equal(assertDefectSourceFacts(multi,white),true);
for(const patch of [{quantity:15},{quantity:6},{unit:'단'}])assert.throws(()=>assertDefectSourceFacts(multi,{...white,...patch}));
const whistler='43차 알스트로메리아 불량\n태림원예\n휘슬러 16단';
assert.throws(()=>assertDefectSourceFacts(whistler,{customerAliases:['주광'],itemTokens:['휘슬러'],quantity:16,unit:'단'}));
assert.equal(assertDefectSourceFacts(whistler,{customerAliases:['태림원예'],itemTokens:['휘슬러'],quantity:16,unit:'단'}),true);
const solo='43-1차 중국 불량\n태림원예\n솔로미오 Ard 15단\n솔로미오 striplefly 10단';
assert.throws(()=>assertDefectSourceFacts(solo,{customerAliases:['태림원예'],itemTokens:['cliff'],quantity:15,unit:'단'}));
assert.throws(()=>assertDefectSourceFacts(solo,{customerAliases:['태림원예'],itemTokens:['striplefly'],quantity:15,unit:'단'}));
assert.equal(assertDefectSourceFacts(solo,{customerAliases:['태림원예'],itemTokens:['striplefly'],quantity:10,unit:'단'}),true);
assert.throws(()=>assertDefectSourceFacts('태림원예A\n휘슬러 16단',{customerAliases:['태림원예'],itemTokens:['휘슬러'],quantity:16,unit:'단'}));
console.log('source facts: Brut5vs15, same-line white25/blue6, customer mix, Solomio variety/quantity, grade suffix and unit near-misses passed');
