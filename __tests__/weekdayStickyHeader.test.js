import assert from 'node:assert/strict';
import { weekdayStickyHeaderLayout as layout,observeWeekdayStickyHeader } from '../lib/weekdayStickyHeader.js';
const geometry={viewport:{left:210,width:1694},header:{top:-20,height:160},table:{bottom:900,width:2830},scrollTop:70};
assert.deepEqual(layout(geometry),{left:210,top:70,width:1694,height:160,tableWidth:2830});
assert.equal(layout({...geometry,header:{top:100,height:160}}),null,'original header is sufficient before scrolling');
assert.equal(layout({...geometry,table:{bottom:200,width:2830}}),null,'hide before table bottom to avoid covering following content');
assert.equal(layout({...geometry,viewport:{left:0,width:0}}),null,'hidden tabs do not retain an overlay');
assert.equal(layout({...geometry,viewport:{left:0,width:360},scrollTop:0}).width,360,'small screens preserve measured viewport');
const events=()=>({listeners:new Map(),addEventListener(key,fn){this.listeners.set(key,fn);},removeEventListener(key){this.listeners.delete(key);}});
const win={...events(),getComputedStyle:()=>({overflowY:'auto'}),requestAnimationFrame:fn=>{win.next=fn;return 1;},cancelAnimationFrame:()=>{win.next=null;}};
const doc={...events(),defaultView:win,body:{}};
const scroller={parentElement:doc.body,scrollHeight:2000,clientHeight:1000,getBoundingClientRect:()=>({top:70})};
const header={getBoundingClientRect:()=>geometry.header};
const table={querySelector:()=>header,getBoundingClientRect:()=>geometry.table};
const viewport={ownerDocument:doc,parentElement:scroller,scrollLeft:450,querySelector:()=>table,getBoundingClientRect:()=>geometry.viewport};
const overlay={scrollLeft:0},updates=[];
const cleanup=observeWeekdayStickyHeader(viewport,{getOverlay:()=>overlay,onLayout:value=>updates.push(value)});
win.next();assert.equal(updates.length,1);assert.equal(overlay.scrollLeft,450);
viewport.scrollLeft=900;doc.listeners.get('scroll')();win.next();
assert.equal(overlay.scrollLeft,900);assert.equal(updates.length,1,'horizontal synchronization does not rerender the matrix');
geometry.header={top:100,height:160};doc.listeners.get('scroll')();win.next();assert.equal(updates.at(-1),null);
cleanup();assert.equal(doc.listeners.size,0);assert.equal(win.listeners.size,0);
console.log('Weekday page sticky header: measured bounds, table bottom, hidden/small viewport, horizontal sync without rerenders and cleanup passed');
