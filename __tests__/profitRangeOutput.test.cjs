const assert = require('node:assert/strict');
const fs = require('node:fs');
const XLSX = require('xlsx-js-style');
module.exports = (async () => {
  const { outputScope, outputWeeks, collectOutput, combineOutputBooks, outputPrintHtml } = await import('../lib/profitRangeOutput.mjs');
  const { buildProfitReportXlsx } = await import('../lib/profitReportExcel.js');
  assert.deepEqual(outputScope('2026', '1'), { year: '2026', major: '01' });
  for (const [y, m] of [[null, 1], ['2026', 0], ['2026', 54], ['2026', '1-01'], ['2026x', 1]]) assert.throws(() => outputScope(y, m));
  assert.equal(outputWeeks('2026', 41).length, 41);
  assert.deepEqual(outputWeeks('2026', 41, ['41', '1', '26', '26']), ['01', '26', '41']);
  assert.throws(() => outputWeeks('2026', 2, []));
  assert.throws(() => outputWeeks('2026', 2, ['3']));
  const sample = { C: 1000, E: 200, F: 0, I: 1300, J: -300, K: -0.3, D: 0.5, U: 0.1 };
  const make = (year, major) => ({ year, major, workbook: buildProfitReportXlsx({ major,
    rows: [{ category: '에콰도르', confirmed: true, calc: sample }], confirmedTotals: sample,
    note: '<script>alert(1)</script> 조정 확인', visibleCols: ['C','E','F','I','J','K'], returnWorkbook: true, displaySheetFirst: true }) });
  const calls = [];
  const items = await collectOutput({ year: '2026', major: '03', fetchWeek: async (y, m) => { calls.push([y,m]); return make(y,m); } });
  assert.deepEqual(calls, [['2026','01'],['2026','02'],['2026','03']]);
  const wb = combineOutputBooks(items);
  assert.deepEqual(wb.SheetNames, ['01차','01차 원본','02차','02차 원본','03차','03차 원본']);
  const saved = XLSX.read(XLSX.write(wb, { type: 'buffer', bookType: 'xlsx', cellStyles: true }), { cellStyles: true, cellNF: true });
  const original = saved.Sheets['03차 원본'];
  const row = Object.keys(original).find(key => /^B\d+$/.test(key) && original[key].v === '에콰도르').slice(1);
  assert.equal(original[`J${row}`].v, -300);
  assert.equal(original[`K${row}`].v, -0.3);
  assert.equal(original[`F${row}`].v, 0);
  assert.equal(saved.Sheets['01차'].A1.s.fgColor.rgb, '17365D');
  assert.equal(saved.Workbook.Names.filter(n => n.Name === '_xlnm.Print_Area').length, 6);
  assert.match(saved.Sheets['03차'].A1.v, /2026년 3차/);
  const adjustments = buildProfitReportXlsx({major: 3, rows: [{category:'에콰도르',confirmed:true,calc:{...sample,AC:100,AJ:-50}}],visibleCols:['AC','AJ'],returnWorkbook:true});
  const adjustmentRows = XLSX.utils.sheet_to_json(adjustments.Sheets['화면표시(선택컬럼)'],{header:1});
  assert.deepEqual(adjustmentRows[3],['품명','매출조정','이익조정']);
  assert.deepEqual(adjustmentRows.find(r=>r[0]==='에콰도르'),['에콰도르',100,-50]);
  assert.throws(() => combineOutputBooks([items[0], make('2025', '02')]));
  assert.throws(() => combineOutputBooks([items[0], items[0]]));
  await assert.rejects(collectOutput({ year: '2026', major: 1, fetchWeek: async () => make('2025','01') }), /응답 범위/);
  await assert.rejects(collectOutput({ year: '2026', major: 2, fetchWeek: async (_,m) => { if(m==='02') throw Error('network'); return make('2026',m); } }), /2차 조회 실패/);
  const abort = new AbortController();
  await assert.rejects(collectOutput({ year: '2026', major: 2, signal: abort.signal, fetchWeek: async (y,m) => { abort.abort(); return make(y,m); } }));
  const html = outputPrintHtml([items[0],items[2]], ws => XLSX.utils.sheet_to_json(ws,{header:1,raw:false,defval:''}));
  assert.match(html, /2026년 1차/); assert.match(html, /2026년 3차/); assert.doesNotMatch(html, /2026년 2차/);
  assert.doesNotMatch(html, /<script>/); assert.match(html, /&lt;script&gt;/); assert.match(html, /-30.00%/);
  const api = fs.readFileSync('pages/api/sales/profit-report-output.js','utf8');
  assert.match(api, /req.method !== 'GET'/); assert.match(api, /preferLive: true/);
  assert.doesNotMatch(api, /snapshotRefresh|saveManual|refreshProfitReportSnapshot|\b(?:INSERT INTO|UPDATE dbo|DELETE FROM|MERGE INTO)\b/i);
  const reads = [];
  const context = {module:{exports:null},withAuth: fn=>fn,outputScope,buildProfitReportXlsx,
    loadWeeklyReportPayload:async (m,y,options)=>{reads.push([m,y,options.preferLive]);return {rows:[{category:'에콰도르',confirmed:true,calc:sample}],confirmed:{revisionNo:1},confirmedTotals:sample};}};
  require('node:vm').runInNewContext(api.replace(/^import .+;\r?\n/gm,'').replace('export default withAuth(', 'module.exports = withAuth('),context);
  const request=async(method,query)=>{const res={code:200,headers:{},setHeader(k,v){this.headers[k]=v},status(n){this.code=n;return this},json(data){this.data=data;return this}};await context.module.exports({method,query},res);return res;};
  assert.equal((await request('POST',{year:'2026',week:'1'})).code,405);
  assert.equal((await request('GET',{week:'1'})).code,400);
  assert.equal((await request('GET',{year:'2026',week:'1',cols:'invalid'})).code,400);
  assert.equal(reads.length,0);
  const valid=await request('GET',{year:'2026',week:'1',cols:'C,J,K,AC,AJ'});
  assert.equal(valid.code,200);assert.equal(valid.headers['Cache-Control'],'private, no-store');
  assert.deepEqual(reads,[['01','2026',true]]);
  assert.equal(valid.data.workbook.Sheets['주차별 매출이익 보고서'][`K${row}`].v,-0.3);
  console.log('profitRangeOutput: PASS (scope, confirmed values, 0, styles, print selection, failures, cancellation)');
})().catch(e => { console.error(e); process.exitCode = 1; });
