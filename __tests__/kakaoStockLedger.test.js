import assert from 'node:assert/strict';
import {calculateLedger,ledgerCopy,analyzeLedgerText,validLedgerWeek} from '../lib/kakaoStockLedger.js';
const base='문라이트 3\n노비아 2\n쥬리고 1\n---------------\n화이트 10\n블루 3\n버건디 1';
const event=(product,qty,mode='ADD',extra={})=>({product,qty,mode,customer:'주광',unit:'박스',...extra});
const events=[event('노비아',1,'BASELINE'),event('문라이트',1),event('노비아',1,'CANCEL')];
assert.equal(ledgerCopy(calculateLedger(base,events)), '문라이트 2 시작3 주광 0>1(3>2)\n노비아 2 시작2 주광 1>0(1>2)\n쥬리고 1\n---------------\n화이트 10\n블루 3\n버건디 1');
assert.equal(calculateLedger(base,[event('문라이트',0,'SET')]).rows[0].remaining,3);
assert.equal(calculateLedger(base,[event('문라이트',4)]).rows[0].remaining,-1);
assert.throws(()=>calculateLedger(base,[event('노비아',1,'CANCEL')]),/기존 주문/);
assert.throws(()=>calculateLedger(base,[event('없는품목',1)]),/없습니다/);
assert.throws(()=>calculateLedger(base,[event('문라이트',1,'ADD',{unit:'송이'})]),/단위/);
assert.throws(()=>calculateLedger('문라이트 3\n문라이트 2',[]),/중복/);
assert.throws(()=>calculateLedger(base,[event('문라이트','')]),/수량/);
assert.throws(()=>calculateLedger(base,[event('문라이트',Infinity)]),/수량/);
assert.equal(calculateLedger(base,[event('문라이트',1,'ADD',{voided:true})]).rows[0].remaining,3);
assert.equal(calculateLedger(base.replace('문라이트 3','문라이트 5'),events).rows[0].remaining,4);
const raw='43-1 콜 카네이션 변경사항\n주광\n문라이트 1추가\n노비아 1취소';
assert.equal(analyzeLedgerText(raw,base,'2026-43-01').changes.length,2);
assert.deepEqual(analyzeLedgerText(raw,base,'2026-43-01').errors,[]);
assert.ok(analyzeLedgerText('2025-'+raw,base,'2026-43-01').errors.length);
assert.ok(analyzeLedgerText(raw,base,'2026-44-01').errors.length);
assert.ok(analyzeLedgerText('주광\n문라이트 전부취소',base,'2026-43-01').errors.length);
assert.ok(analyzeLedgerText('주광\n문라이트 1추가\n불명확한 메모',base,'2026-43-01').errors.length);
assert.equal(validLedgerWeek('2026-43-01'),true);
assert.equal(validLedgerWeek('43-01'),false);
assert.equal(validLedgerWeek('2026-00-01'),false);
assert.equal(calculateLedger('문라이트 2박스 + 3송이',[event('문라이트',1,'ADD',{unit:'송이'})]).rows[0].remainingDetail,2);
console.log('kakao stock ledger: example, corrections, zero, shortage, units, unknown text, cross-year passed');
